import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { basename, join, sep } from "node:path";
import { checkFlag, displayPath, message, posixPath, ROOT, runCli, writeGenerated } from "./runtime.ts";

export type Label = readonly [name: string, description: string, glob: string];

export function groupDirs(root: string): string[] {
  const groups: string[] = [];
  const scan = (relative: string): void => {
    for (const entry of readdirSync(join(root, "guides", relative), { withFileTypes: true })) {
      if (entry.isSymbolicLink()) throw new Error(`guides/${relative}/${entry.name}: symbolic links are not supported`);
      if (!entry.isDirectory()) continue;
      const next = join(relative, entry.name);
      if (!relative || existsSync(join(root, "guides", next, "README.md"))) groups.push(next);
      scan(next);
    }
  };
  scan("");
  return groups.sort();
}

export function displayName(root: string, relative: string): string {
  const readme = join(root, "guides", relative, "README.md");
  if (existsSync(readme)) {
    const heading = readFileSync(readme, "utf8")
      .split(/\r?\n/)
      .find((line) => line.startsWith("# "));
    if (heading) return heading.slice(2).trim();
  }
  return basename(relative)
    .split("-")
    .map((part) => (["xss", "csrf"].includes(part) ? part.toUpperCase() : part.charAt(0).toUpperCase() + part.slice(1)))
    .join(" ");
}

export function guideLabels(root: string): Label[] {
  const groups = groupDirs(root);
  const counts = new Map<string, number>();
  for (const group of groups) counts.set(basename(group), (counts.get(basename(group)) ?? 0) + 1);
  const names = new Set<string>();
  return groups.map((group): Label => {
    const name = counts.get(basename(group)) === 1 ? basename(group) : group.split(sep).join("-");
    if (names.has(name)) throw new Error(`Guide category paths produce duplicate label ${JSON.stringify(name)}`);
    names.add(name);
    const display = displayName(root, group);
    return [
      name,
      group.includes(sep) ? `Changes to ${display} guides` : `Changes to guides in the ${display} category`,
      `guides/${posixPath(group)}/**`,
    ];
  });
}

export function color(name: string): string {
  return createHash("sha1").update(name, "utf8").digest("hex").slice(0, 6);
}

export function render(root: string, labels: readonly Label[]): Map<string, string> {
  const header =
    "# This file is generated by scripts/sync-guide-labels.ts.\n# Run `pnpm generate:labels` after changing guide groups.\n# DO NOT EDIT THIS FILE MANUALLY.\n\n";
  // JSON string quoting is valid YAML and escapes headings containing quotes and backslashes.
  const quote = JSON.stringify;
  const labeler = labels
    .map(
      ([name, , glob]) =>
        `${quote(name)}:\n  - changed-files:\n      - any-glob-to-any-file:\n          - ${quote(glob)}\n`,
    )
    .join("\n");
  const descriptions = [...labels]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(
      ([name, description]) =>
        `- name: ${quote(name)}\n  description: ${quote(description)}\n  color: ${quote(color(name))}\n`,
    )
    .join("\n");
  return new Map([
    [join(root, ".github/labeler.yaml"), `${(header + labeler).trimEnd()}\n`],
    [join(root, ".github/labels.yaml"), `${(header + descriptions).trimEnd()}\n`],
  ]);
}

export function main(args: string[], root = ROOT): number {
  const check = checkFlag(args);
  const generated = render(root, guideLabels(root));
  const errors: string[] = [];
  for (const [path, content] of generated) {
    try {
      const updated = writeGenerated(path, content, check, "pnpm generate:labels");
      console.log(`${displayPath(root, path)} is ${updated ? "updated" : "up to date"}.`);
    } catch (error) {
      errors.push(message(error));
    }
  }
  if (errors.length) {
    console.error(errors.join("\n"));
    return 1;
  }
  return 0;
}
runCli(import.meta.url, main);
